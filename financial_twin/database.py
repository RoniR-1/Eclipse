def initialize_database(database_url, data_root=ROOT):
    with psycopg.connect(database_url) as connection:
        with connection.cursor() as cursor:
            cursor.execute("SELECT pg_advisory_xact_lock(739628105)")
            for name, _, definition in TABLES:
                cursor.execute(sql.SQL("CREATE TABLE IF NOT EXISTS {} ({})").format(sql.Identifier(name), sql.SQL(definition)))
            cursor.execute("""CREATE TABLE IF NOT EXISTS life_event_knowledge (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                event_type text NOT NULL,
                normalized_key text NOT NULL UNIQUE,
                display_name text NOT NULL,
                keywords jsonb NOT NULL DEFAULT '[]'::jsonb,
                params jsonb NOT NULL DEFAULT '{}'::jsonb,
                source_urls jsonb NOT NULL DEFAULT '[]'::jsonb,
                source_type text NOT NULL CHECK (source_type IN ('preseeded', 'ai_web_search')),
                created_at timestamptz NOT NULL DEFAULT now(),
                updated_at timestamptz NOT NULL DEFAULT now(),
                expires_at timestamptz
            )""")
            cursor.execute("ALTER TABLE life_event_knowledge ADD COLUMN IF NOT EXISTS note text NOT NULL DEFAULT ''")
            seed_common_events(cursor)
            for table in ("accounts", "assets", "liabilities", "goals", "cash_balances", "scenario_assumptions", "life_events", "transactions"):
                cursor.execute(sql.SQL("CREATE INDEX IF NOT EXISTS {} ON {} (profile_id)").format(sql.Identifier(f"{table}_profile_id_idx"), sql.Identifier(table)))
            for name, _, _ in TABLES:
                cursor.execute(sql.SQL("SELECT EXISTS (SELECT 1 FROM {} LIMIT 1)").format(sql.Identifier(name)))
                if cursor.fetchone()[0]:
                    return False
            if not Path(data_root).exists():
                return False
            for name, relative_path, _ in TABLES:
                path = Path(data_root) / relative_path
                cursor.execute("SELECT column_name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = %s ORDER BY ordinal_position", (name,))
                columns = [row[0] for row in cursor.fetchall()]
                with path.open(encoding="utf-8-sig", newline="") as source:
                    if next(csv.reader(source), None) != columns:
                        raise ValueError(f"CSV header does not match {name}: {path}")
                with path.open("rb") as source:
                    with cursor.copy(sql.SQL("COPY {} FROM STDIN WITH (FORMAT CSV, HEADER TRUE)").format(sql.Identifier(name))) as copy:
                        while chunk := source.read(1024 * 1024):
                            copy.write(chunk)
    return True


def seed_common_events(cursor):
    university_url = "https://www.swissuniversities.ch/en/themen/lehre-studium/information-on-studies/tuition-fees/tuition-fees-at-universities"
    uas_url = "https://www.swissuniversities.ch/en/themen/lehre-studium/information-on-studies/tuition-fees/tuition-fees-at-uas"
    institutions = (
        ("eth-zurich", "ETH Zurich", 730, 730, university_url, ["eth", "ethz"]),
        ("epfl", "EPFL", 730, 730, university_url, []),
        ("unil", "University of Lausanne", 500, 500, university_url, ["unil"]),
        ("uzh", "University of Zurich", 720, 720, university_url, ["uzh"]),
        ("bern", "University of Bern", 850, 850, university_url, ["unibe"]),
        ("basel", "University of Basel", 850, 850, university_url, ["unibas"]),
        ("unige", "University of Geneva", 435, 435, university_url, ["unige"]),
        ("usi", "Università della Svizzera italiana", 2000, 2000, university_url, ["usi"]),
        ("hsg", "University of St. Gallen", 1070, 1284, university_url, ["hsg"]),
        ("zhaw", "ZHAW", 720, 720, uas_url, []),
        ("hes-so", "HES-SO", 700, 700, uas_url, ["hes so"]),
    )
    ttl = max(1, int(os.environ.get("LIFE_EVENT_CACHE_TTL_DAYS", "180")))
    for slug, name, bachelor_fee, master_fee, url, aliases in institutions:
        for degree, duration in (("bachelor", 36), ("master", 24)):
            fee = bachelor_fee if degree == "bachelor" else master_fee
            is_uas = url == uas_url
            gross_income = 80300 if is_uas else 80900
            benchmark = "UAS bachelor" if is_uas else "university master"
            income_note = (
                f"Income assumes 80% net of CHF {gross_income:,} annual gross, "
                f"the FSO 2022 cohort {benchmark} median one year after graduation. "
                "This is a broad proxy for both degree levels, not an institution-specific salary."
            )
            cursor.execute("""INSERT INTO life_event_knowledge
                (event_type, normalized_key, display_name, keywords, params, source_urls, source_type, expires_at, note)
                VALUES (%s, %s, %s, %s::jsonb, %s::jsonb, %s::jsonb, 'preseeded', now() + %s * interval '1 day', %s)
                ON CONFLICT (normalized_key) DO NOTHING""", (
                "education", f"education:{degree}:{slug}", f"{degree.title()} — {name}",
                json.dumps([f"{degree} {alias}" for alias in [name, *aliases]] + [f"{degree}'s at {name}"]),
                json.dumps({"duration_months": duration, "annual_tuition_chf": fee * 2, "income_after_chf": round(gross_income * 0.8 / 12)}),
                json.dumps([url, "https://statistik.admin.ch/fr/asset/32172111"]), ttl,
                "Domestic tuition for 2026–27 excludes other fees; foreign tuition may be higher. " + income_note,
            ))
    cities = (
        ("Lausanne", "lausanne", 12709, 417, 0.05),
        ("Zurich", "zurich", 17814, 486, 0.02),
        ("Geneva", "geneve", 16042, 513, 0.04),
        ("Bern", "berne", 9530, 373, 0.04),
        ("Basel", "bale", 11613, 343, 0.04),
    )
    for city, city_slug, price_per_m2, annual_rent_per_m2, fees in cities:
        for kind in ("rent", "buy"):
            if kind == "rent":
                params = {
                    "new_rent_chf": round(annual_rent_per_m2 * 80 / 12),
                    "deposit_months": 3,
                    "moving_cost_chf": 1500,
                }
            else:
                params = {
                    "purchase_price_chf": price_per_m2 * 80,
                    "down_payment_share": 0.2,
                    "purchase_fees_share": fees,
                    "mortgage_interest_rate": 0.02,
                    "annual_maintenance_share": 0.01,
                }
            action = "buying" if kind == "buy" else "renting"
            aliases = [f"{kind} {city}", f"{action} in {city}", f"{action} an apartment in {city}"]
            if city == "Lausanne":
                aliases.extend([f"{kind} vaud", f"{action} in vaud"])
            cursor.execute("""INSERT INTO life_event_knowledge
                (event_type, normalized_key, display_name, keywords, params, source_urls, source_type, expires_at, note)
                VALUES ('housing_change', %s, %s, %s::jsonb, %s::jsonb, %s::jsonb, 'preseeded', now() + %s * interval '1 day', %s)
                ON CONFLICT (normalized_key) DO NOTHING""", (
                f"housing_change:{kind}:{city.lower()}", f"{kind.title()} in {city}",
                json.dumps(aliases),
                json.dumps(params), json.dumps([f"https://realadvisor.ch/fr/prix-m2-immobilier/ville-{city_slug}", "https://www.ch.ch/en/taxes-and-finances/types-of-taxation/taxation-of-real-estate"]), ttl,
                f"Assumes an 80 m² apartment using RealAdvisor October 2026 modelled median price CHF {price_per_m2}/m² and annual rent CHF {annual_rent_per_m2}/m². Fees, moving and financing are illustrative assumptions; actual values depend on the property and lender.",
            ))


def initialize_from_environment():
    database_url = os.environ.get("DATABASE_URL")
    if not database_url:
        raise RuntimeError("DATABASE_URL must be set to a PostgreSQL connection URL")
    return initialize_database(database_url)
